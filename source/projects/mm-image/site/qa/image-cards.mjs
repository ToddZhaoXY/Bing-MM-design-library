import { fileURLToPath } from 'node:url';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import fs from 'node:fs/promises';
import path from 'node:path';
const project=fileURLToPath(new URL('../../',import.meta.url));
const out=path.join(project,'design/fy25-cards/qa');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1600,height:1100},deviceScaleFactor:1});
const errors=[];const badRequests=[];
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)badRequests.push({url:r.url(),status:r.status()})});
const base=process.env.QA_URL||'http://127.0.0.1:5198/Bing-MM-design-library/mm-image.html';
await page.goto(base,{waitUntil:'networkidle'});
const sizes=['2x2','3x2','4x2','5x2','2x4','3x4','4x4','5x4','6x4','8x4','9x4','11x4','11x2'];
const cases=[];
for(const size of sizes){
 await page.goto(base+'#/c/image-card-'+size,{waitUntil:'networkidle'});
 await page.waitForSelector('[data-image-card]');
 const options=await page.locator('#f-variant option').evaluateAll(nodes=>nodes.map(n=>n.value));
 for(const variant of options){
  await page.locator('#f-variant').selectOption(variant);
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>[...document.querySelectorAll('[data-image-card] img')].every(i=>i.complete&&i.naturalWidth>0));
  const card=page.locator('[data-image-card]');
  const result=await card.evaluate(el=>{
   const s=getComputedStyle(el);const b=el.getBoundingClientRect();
   return {id:el.dataset.sourceNode,variant:el.dataset.cardVariant,width:parseFloat(s.width),height:parseFloat(s.height),box:{x:b.x,y:b.y,width:b.width,height:b.height},images:el.querySelectorAll('img').length,assets:[...el.querySelectorAll('img')].map(i=>({src:i.getAttribute('src'),width:i.getBoundingClientRect().width,height:i.getBoundingClientRect().height,loaded:i.complete&&i.naturalWidth>0})),nestedButtons:el.querySelectorAll('button button').length};
  });
  const filename=`${size}-${result.id.replace(':','-')}.png`;
  await card.screenshot({path:path.join(out,filename)});
  cases.push({size,label:variant,...result,screenshot:filename});
 }
}
await page.goto(base+'#/c/image-card-3x2',{waitUntil:'networkidle'});
await page.locator('#f-variant').selectOption({index:1});
await page.locator('[data-card-action="more"]').first().click();
const gallery=await page.locator('dialog[open]').isVisible();
await page.keyboard.press('Escape');
const galleryClosed=await page.locator('dialog[open]').count()===0;
await page.goto(base+'#/playground',{waitUntil:'networkidle'});
await page.locator('.pg__add').filter({hasText:'Image cards'}).click();
await page.locator('#pg-size').selectOption('3x2');
await page.locator('#pg-variant').selectOption('Image carousel');
await page.locator('[data-image-card] [data-card-action="scroll"]').click();
await page.waitForTimeout(500);
const scrollBefore=await page.locator('[data-image-card]').evaluate(el=>[...el.querySelectorAll('*')].filter(n=>n.scrollLeft>0).map(n=>n.scrollLeft));
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Export HTML',exact:true}).click();
const download=await downloadPromise;
const exportPath=path.join(out,'exported-card.html');
await download.saveAs(exportPath);
const html=await fs.readFile(exportPath,'utf8');
const offline=await browser.newPage();
await offline.route('**/*',route=>route.abort());
await offline.setContent(html,{waitUntil:'load'});
const exported=await offline.evaluate(()=>({images:[...document.querySelectorAll('img')].map(i=>({embedded:i.src.startsWith('data:'),loaded:i.complete&&i.naturalWidth>0})),font:getComputedStyle(document.querySelector('[data-image-card]')).fontFamily,scrollAfter:[...document.querySelectorAll('[data-export-scroll-x]')].map(n=>n.scrollLeft)}));
exported.scrollBefore=scrollBefore;
await offline.screenshot({path:path.join(out,'offline-mixed-export.png'),fullPage:true});
await offline.close();
await page.goto(base+'#/c/image-card-11x4',{waitUntil:'networkidle'});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:path.join(out,'wide-desktop.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(100);
const mobile=await page.evaluate(()=>({viewport:innerWidth,documentWidth:document.documentElement.scrollWidth,preview:document.querySelector('.preview').getBoundingClientRect().toJSON()}));
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:path.join(out,'wide-mobile.png'),fullPage:true});
await fs.writeFile(path.join(out,'browser-report.json'),JSON.stringify({cases,errors,badRequests,gallery,galleryClosed,exported,mobile},null,2));
console.log(JSON.stringify({cases:cases.length,errors,badRequests,gallery,galleryClosed,exported,mobile}));
await browser.close();

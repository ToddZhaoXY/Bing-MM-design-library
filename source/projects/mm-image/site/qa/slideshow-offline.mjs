// Fresh, network-disabled fixture. Does not read the user's browser, profile or localhost origin.
import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
import { inlinePage, repo } from '../../../../qa/offline-library.mjs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const output = path.join(repo, 'source/projects/mm-image/design/slideshow/qa')
await fs.mkdir(output, { recursive: true })
const source = JSON.parse(await fs.readFile(path.join(output, '../specification.json'), 'utf8'))
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
  const requests = [], errors = []
  await context.route('**/*', route => { requests.push(route.request().url()); return route.abort() })
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  page.on('pageerror', e => errors.push(e.message))
  // Shared Badge composes its icon path at runtime. Inline that path too, so
  // this origin-free fixture can exercise it without a localhost request.
  const badgeFile = 'mm-image-figma-icon-badge-multi-image.svg'
  const badgeData = `data:image/svg+xml;base64,${(await fs.readFile(path.join(repo, badgeFile))).toString('base64')}`
  async function embedDynamicImages() {
    await page.evaluate(({ file, data }) => {
      for (const img of document.images) if (img.getAttribute('src')?.replace(/^\.\//, '') === file) img.src = data
    }, { file: badgeFile, data: badgeData })
  }
  await page.setContent(await inlinePage('mm-image', '/c/slideshow'), { waitUntil: 'load' })
  await page.waitForSelector('[data-slideshow]')
  await page.evaluate(() => document.fonts.ready)
  const nav = page.locator('.nav__group').filter({ has: page.locator('.nav__group-title', { hasText: 'Cells' }) })
  assert.equal(await nav.getByRole('link', { name: 'SlideShow', exact: true }).count(), 1)
  const cases = []
  for (const variant of source.variants) {
    await page.locator('#f-size').selectOption(variant.size)
    await page.locator('#f-pagination').selectOption(variant.pagination)
    await page.locator('#f-state').selectOption(variant.state)
    await page.mouse.move(0, 0)
    await embedDynamicImages()
    await page.waitForFunction(() => [...document.querySelectorAll('[data-slideshow] img')].every(img => img.complete && img.naturalWidth > 0))
    const geometry = await page.locator('[data-slideshow]').evaluate(el => ({ width: el.offsetWidth, height: el.offsetHeight, node: el.dataset.sourceNode, state: el.dataset.state }))
    assert.equal(geometry.width, variant.dimensions.width)
    assert.equal(geometry.height, variant.dimensions.height)
    assert.equal(geometry.node, variant.figmaNodeId)
    assert.equal(geometry.state, variant.state)
    const link = await page.getByRole('link', { name: 'View in Figma' }).getAttribute('href')
    assert.ok(link.includes('fRSRroY4YFgJSeqLLE0Y38') && link.includes(variant.figmaNodeId.replace(':', '-')))
    await page.locator('[data-slideshow]').screenshot({ path: path.join(output, variant.screenshot) })
    cases.push({ ...geometry, size: variant.size, pagination: variant.pagination })
  }
  await page.getByRole('button', { name: 'Reset to defaults', exact: true }).click()
  const card = page.locator('[data-slideshow]')
  assert.equal(await card.getAttribute('data-state'), 'Default')
  await card.hover()
  assert.equal(await card.getAttribute('data-state'), 'Hover')
  await card.getByRole('button', { name: 'Go to slide 3', exact: true }).click()
  assert.equal(await card.getAttribute('data-slide-index'), '2')
  assert.ok((await page.locator('.code pre').textContent()).includes('initialIndex={2}'))
  await card.press('ArrowLeft')
  assert.equal(await card.getAttribute('data-slide-index'), '1')
  await card.press('End')
  assert.equal(await card.getAttribute('data-slide-index'), '3')
  await card.press('Home')
  assert.equal(await card.getAttribute('data-slide-index'), '0')
  await page.getByRole('button', { name: 'Reset to defaults', exact: true }).click()
  await page.mouse.move(0, 0)
  assert.equal(await card.getAttribute('data-state'), 'Default')
  await page.locator('#f-pagination').selectOption('Bottom arrows')
  assert.deepEqual(await page.locator('#f-state option').allTextContents(), ['Default'])
  assert.equal(await card.getByRole('button', { name: 'Previous slide' }).isDisabled(), true)
  for (let i = 1; i <= 4; i++) {
    await card.getByRole('button', { name: 'Next slide' }).click()
    assert.equal(await card.getAttribute('data-slide-index'), String(i))
  }
  assert.ok((await card.textContent()).includes('See more'))
  assert.equal(await card.getByRole('button', { name: 'Next slide' }).isDisabled(), true)
  await page.getByRole('button', { name: 'Mosaic SDL', exact: true }).click()
  assert.ok((await page.locator('.code pre').textContent()).includes('See more'))
  await page.getByRole('button', { name: 'Reset to defaults', exact: true }).click()
  assert.equal(await card.getAttribute('data-slide-index'), '0')
  await page.locator('#f-pagination').selectOption('Top bars')
  await card.getByRole('button', { name: 'Go to slide 4', exact: true }).click()
  assert.equal(await card.getAttribute('data-slide-index'), '3')
  await page.evaluate(() => window.__qaNavigate('/playground'))
  await page.locator('.pg__surface').filter({ hasText: 'Blank' }).click()
  await page.locator('.pg__add').filter({ hasText: 'SlideShow' }).click()
  await page.locator('#pg-size').selectOption('5:4')
  await page.locator('#pg-pagination').selectOption('Top bars')
  await page.locator('[data-slideshow]').getByRole('button', { name: 'Next slide' }).click()
  assert.equal(await page.locator('[data-slideshow]').getAttribute('data-slide-index'), '1')
  assert.ok((await page.locator('.code pre').first().textContent()).includes('initialIndex={1}'))
  await page.getByRole('button', { name: 'Reset to defaults', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-slideshow]').dataset.slideIndex === '0')
  assert.equal(await page.locator('[data-slideshow]').getAttribute('data-slide-index'), '0')
  page.once('dialog', d => d.accept(JSON.stringify({ version: 1, surface: 'blank', blocks: [{ id: 42, slug: 'slideshow', values: { size: '3:2', pagination: 'Bottom bars', state: 'Hover' }, live: { initialIndex: 2 } }], items: [], suggestions: [] })))
  await page.getByRole('button', { name: 'Load state', exact: true }).click()
  await embedDynamicImages()
  assert.equal(await page.locator('[data-slideshow]').getAttribute('data-slide-index'), '2')
  const downloadWait = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export HTML', exact: true }).click()
  const download = await downloadWait
  const htmlPath = path.join(output, 'standalone-snapshot.html')
  await download.saveAs(htmlPath)
  const html = await fs.readFile(htmlPath, 'utf8')
  assert.ok(html.includes('MM SlideShow Alice') && html.includes('data-slide-index="2"'))
  assert.ok(!/src="(?!data:)/.test(html))
  const snapshot = await context.newPage()
  snapshot.on('pageerror', e => errors.push(e.message))
  await snapshot.setContent(html, { waitUntil: 'load' })
  await snapshot.evaluate(() => document.fonts.ready)
  await snapshot.waitForFunction(() => [...document.images].every(img => img.complete && img.naturalWidth > 0))
  assert.equal(await snapshot.locator('[data-slideshow]').getAttribute('data-slide-index'), '2')
  await snapshot.close()
  await page.evaluate(() => window.__qaNavigate('/c/slideshow'))
  await page.locator('#f-size').selectOption('5:4')
  await embedDynamicImages()
  await page.mouse.move(0, 0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(100)
  const mobile = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }))
  assert.equal(mobile.document, mobile.viewport)
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true })
  assert.deepEqual(errors, [])
  assert.deepEqual(requests, [])
  const report = { mode: 'Isolated network-disabled about:blank fixture; production components + MemoryRouter + built CSS', cases, interactionChecks: ['hover', 'thumbnails', 'ArrowLeft', 'Home', 'End', 'top indicators', 'arrows and end card', 'dependent state', 'JSX selection', 'SDL selection', 'reset', 'palette', 'saved state', 'embedded standalone HTML'], mobile, errors, requests }
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report))
} finally { await browser.close() }

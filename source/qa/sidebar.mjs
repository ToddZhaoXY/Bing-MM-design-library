// No user browser or server origin access: test only local components/CSS in
// isolated about:blank fixtures. All network requests are blocked.
import { inlinePage, repo } from './offline-library.mjs'
import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const out=path.join(repo,'source/qa/sidebar-results')
await fs.mkdir(out,{recursive:true})
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
const results=[]
try {
 for(const library of ['mm-image','aigc','video']) {
  const context=await browser.newContext({viewport:{width:1440,height:1040}})
  const network=[];const errors=[]
  await context.route('**/*',r=>{network.push(r.request().url());return r.abort()})
  const page=await context.newPage()
  page.on('pageerror',e=>errors.push(e.message))
  await page.setContent(await inlinePage(library),{waitUntil:'load'})
  await page.waitForSelector('.nav--tree')
  const components=await page.evaluate(()=>window.__qaComponents)
  const child=components.find(c=>c.partOf)
  const parent=components.find(c=>c.slug===child.partOf)
  const nav=page.locator('.nav--tree')
  const to=async target=>{await page.evaluate(target=>window.__qaNavigate(target),target);await page.waitForTimeout(70)}
  const pathNow=()=>page.evaluate(()=>window.__qaLocation)
  const childLink=nav.locator(`a[href="/c/${child.slug}"]`)
  const parentLink=nav.locator(`a[href="/c/${parent.slug}"]`)
  assert.equal(await childLink.isVisible(),false,'unselected child groups start collapsed')
  await to('/c/'+child.slug)
  assert.equal(await childLink.isVisible(),true,'deep link reveals child')
  assert.equal(await nav.locator('a[aria-current="page"]').count(),1)
  assert.equal(await childLink.getAttribute('aria-current'),'page')
  assert.equal(await parentLink.getAttribute('aria-current'),null)
  const group=parent.tier+'s'
  assert.equal(await nav.getByRole('button',{name:'Collapse '+group,exact:true}).getAttribute('aria-expanded'),'true')
  const style=async locator=>locator.evaluate(el=>{const s=getComputedStyle(el);return {size:parseFloat(s.fontSize),weight:s.fontWeight,color:s.color}})
  const hierarchy={group:await style(nav.getByRole('button',{name:'Collapse '+group,exact:true})),parent:await style(parentLink),child:await style(childLink)}
  assert.ok(hierarchy.group.size<hierarchy.child.size&&hierarchy.child.size<hierarchy.parent.size)
  assert.equal(hierarchy.child.color,'rgb(40, 89, 166)')
  assert.equal(hierarchy.child.weight,'600')
  await nav.getByRole('button',{name:'Collapse '+parent.name,exact:true}).click()
  assert.equal(await childLink.isVisible(),false)
  assert.equal(await pathNow(),'/c/'+child.slug,'folding does not navigate')
  const expand=nav.getByRole('button',{name:'Expand '+parent.name,exact:true})
  await expand.focus();await page.keyboard.press('Space')
  assert.equal(await childLink.isVisible(),true)
  await nav.getByRole('button',{name:'Collapse '+group,exact:true}).click()
  assert.equal(await parentLink.isVisible(),false)
  const expandGroup=nav.getByRole('button',{name:'Expand '+group,exact:true})
  await expandGroup.focus();await page.keyboard.press('Enter')
  assert.equal(await childLink.isVisible(),true)
  await nav.getByRole('button',{name:'Collapse '+parent.name,exact:true}).click()
  await parentLink.click()
  await page.waitForFunction(expected=>window.__qaLocation===expected,'/c/'+parent.slug)
  assert.equal(await pathNow(),'/c/'+parent.slug,'parent label remains a page link')
  await childLink.waitFor({state:'visible'})
  assert.equal(await childLink.isVisible(),true,'entering a parent reveals its children')
  await nav.getByRole('button',{name:'Collapse '+group,exact:true}).click()
  await to('/playground');await to('/c/'+child.slug)
  assert.equal(await childLink.isVisible(),true,'navigation reopens hidden active ancestors')
  const parts=components.filter(c=>c.partOf===parent.slug&&c.slug!==child.slug)
  if(parts.length) {
    hierarchy.inactiveChild=await style(nav.locator(`a[href="/c/${parts[0].slug}"]`))
    assert.ok(Number(hierarchy.inactiveChild.weight)<Number(hierarchy.parent.weight))
    assert.notEqual(hierarchy.inactiveChild.color,hierarchy.parent.color)
  }
  const rail=nav.getByRole('button',{name:'Collapse navigation',exact:true})
  await rail.focus();await page.keyboard.press('Enter')
  assert.equal(await page.locator('#library-navigation').isVisible(),false)
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(()=>Boolean(document.activeElement?.closest('#library-navigation'))),false,'hidden links leave keyboard order')
  await nav.getByRole('button',{name:'Expand navigation',exact:true}).click()
  assert.equal(await childLink.isVisible(),true)
  assert.equal(await nav.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'long labels do not overflow')
  if(library==='mm-image') {
    const molecules=nav.locator('.nav__group').filter({has:page.locator('.nav__group-title',{hasText:'Molecules'})})
    assert.equal((await molecules.locator('.nav__list > .nav__node > .nav__row > a').allTextContents()).at(-1),'Image cards')
  }
  const controls=await nav.locator('button[aria-controls]').evaluateAll(buttons=>buttons.map(button=>({id:button.getAttribute('aria-controls'),exists:Boolean(document.getElementById(button.getAttribute('aria-controls')))})))
  assert.ok(controls.every(c=>c.exists))
  await page.evaluate(()=>window.scrollTo(0,0))
  await nav.screenshot({path:path.join(out,library+'-sidebar.png')})
  await page.screenshot({path:path.join(out,library+'-desktop.png')})
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal(await nav.locator('.nav__chevron').first().evaluate(el=>getComputedStyle(el).transitionDuration),'0s')
  await page.setViewportSize({width:390,height:844})
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:path.join(out,library+'-mobile.png'),fullPage:true})
  const mobile=await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth,nav:document.querySelector('.nav').clientWidth}))
  assert.equal(mobile.width,mobile.document)
  assert.deepEqual(errors,[]);assert.deepEqual(network,[])
  results.push({library,parent:parent.name,child:child.name,hierarchy,controls:controls.length,componentLinks:await nav.locator('a[href^="/c/"]').count(),mobile,errors,network})
  await context.close()
 }
 const touch=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
 await touch.route('**/*',route=>route.abort())
 const page=await touch.newPage();await page.setContent(await inlinePage('mm-image','/c/meta-data'))
 await page.waitForSelector('.nav__branch-toggle')
 const target=await page.locator('.nav__branch-toggle').first().boundingBox()
 assert.ok(target.width>=44&&target.height>=44)
 await touch.close()
 assert.deepEqual(results.map(r=>r.hierarchy.group.size),[11,11,11])
 assert.deepEqual(results.map(r=>r.hierarchy.parent.size),[14,14,14])
 assert.deepEqual(results.map(r=>r.hierarchy.child.size),[13,13,13])
 await fs.writeFile(path.join(out,'report.json'),JSON.stringify({mode:'local isolated fixture, no browser/origin access',results,touchTarget:target},null,2))
 console.log(JSON.stringify({libraries:results.map(r=>r.library),hierarchy:'11 / 14 / 13 px',passed:true,touchTarget:target}))
} finally {await browser.close()}
